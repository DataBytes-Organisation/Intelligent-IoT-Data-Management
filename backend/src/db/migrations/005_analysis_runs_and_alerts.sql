-- ============================================================
-- TABLE 1: ANALYSIS RUNS
-- Stores one record for each completed analysis.
-- ============================================================

CREATE TABLE IF NOT EXISTS analysis_runs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL
        REFERENCES auth_users(id) ON DELETE RESTRICT,

    dataset_id INTEGER NOT NULL
        REFERENCES datasets(id) ON DELETE RESTRICT,

    streams JSONB NOT NULL DEFAULT '[]'::jsonb,

    settings JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- TABLE 2: ANALYSIS ALERTS
-- Stores individual alerts generated by an analysis.
-- The id column is the backend-generated alert_id.
-- ============================================================

CREATE TABLE IF NOT EXISTS analysis_alerts (
    id UUID PRIMARY KEY,

    run_id UUID NOT NULL
        REFERENCES analysis_runs(id) ON DELETE CASCADE,

    timestamp TIMESTAMPTZ NOT NULL,

    alert_type TEXT NOT NULL,

    target JSONB NOT NULL,

    method TEXT NOT NULL,

    message TEXT NOT NULL,

    source JSONB NOT NULL,

    score DOUBLE PRECISION,

    score_metadata JSONB,

    severity TEXT,

    time_window JSONB,

    supporting_values JSONB
);

-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_analysis_runs_user_created
    ON analysis_runs (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_analysis_alerts_run
    ON analysis_alerts (run_id);

